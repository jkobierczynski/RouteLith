//! Regenerates `crates/rl-fed/src/pb.rs`. Run from this directory:
//! `cargo run`.
fn main() {
    // protoc comes from the protoc-bin-vendored crate: no system protoc.
    let protoc = protoc_bin_vendored::protoc_bin_path().expect("vendored protoc");
    // SAFETY: single-threaded, before anything reads the environment.
    unsafe { std::env::set_var("PROTOC", protoc) };
    let out = tempdir();
    tonic_prost_build::configure()
        .out_dir(&out)
        .build_transport(false)
        .compile_protos(&["../proto/agent.proto"], &["../proto"])
        .expect("protoc");
    let code = std::fs::read_to_string(out.join("routelith.agent.v1.rs")).expect("generated file");
    let head = "// @generated by crates/rl-fed/gen from proto/agent.proto. Do not edit.\n\
                #![allow(clippy::all, clippy::pedantic, missing_debug_implementations, unreachable_pub)]\n\n";
    std::fs::write("../src/pb.rs", format!("{head}{code}")).expect("write pb.rs");
    println!("wrote ../src/pb.rs");
}

fn tempdir() -> std::path::PathBuf {
    let d = std::env::temp_dir().join(format!("rl-fed-gen-{}", std::process::id()));
    std::fs::create_dir_all(&d).expect("temp dir");
    d
}
